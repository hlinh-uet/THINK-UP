import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
import {initializeDemoDatabase} from '../scripts/seed-demo.mjs';
import {messageStore} from '../lib/message-store.ts';
const require=createRequire(import.meta.url);
const {Miniflare}=createRequire(require.resolve('wrangler/package.json'))('miniflare');
const status=code=>error=>error.status===code;

test('D1 chat preserves private cross-role history, snapshots, unread markers, retries and pagination',async()=>{
  const mf=new Miniflare({modules:true,script:'export default {fetch(){return new Response("test")}}',compatibilityDate:'2026-05-15',d1Databases:['DB']});
  try{
    const db=await mf.getD1Database('DB');await initializeDemoDatabase(db);
    await db.batch(['student','lecturer','admin','inactive'].map(role=>db.prepare('INSERT INTO users VALUES (?,?,?,?,?,?)').bind(role,role+'@test.local','TEST '+role,role==='inactive'?'student':role,role==='inactive'?0:1,new Date().toISOString())));
    const store=messageStore(db),key=randomUUID(),sent=await store.send('student','lecturer','  TEST hello\nXin chào  ',key);
    assert.equal(sent.body,'TEST hello\nXin chào');assert.equal(sent.senderName,'TEST student');assert.equal(sent.senderRole,'student');
    const retry=await store.send('student','lecturer',sent.body,key);assert.equal(retry.id,sent.id);
    await assert.rejects(store.send('student','lecturer','different',key),status(409));
    await assert.rejects(store.send('student','admin',sent.body,key),status(409));
    const concurrentId=randomUUID(),concurrent=await Promise.all(Array.from({length:5},()=>store.send('lecturer','student','TEST concurrent',concurrentId)));
    assert.equal(new Set(concurrent.map(m=>m.id)).size,1);
    assert.equal(await db.prepare('SELECT COUNT(*) AS n FROM chat_conversations').first('n'),1);
    assert.equal(await db.prepare('SELECT COUNT(*) AS n FROM chat_messages').first('n'),2);
    assert.equal(await store.unread('student'),1);assert.equal(await store.unread('lecturer'),1);assert.equal(await store.unread('admin'),0);
    const inbox=await store.inbox('student');assert.equal(inbox.conversations[0].peer.role,'lecturer');assert.equal(inbox.unreadTotal,1);
    assert.deepEqual(Object.keys(inbox.contacts[0]).sort(),['active','id','name','role']);assert.ok(!inbox.contacts.some(p=>p.id==='inactive'||p.id==='student'));
    assert.equal((await store.inbox('admin')).conversations.length,0);
    assert.equal((await store.thread('admin','student')).messages.length,0);
    await assert.rejects(store.markRead('admin',sent.conversationId,sent.id),status(404));
    await store.markRead('lecturer',sent.conversationId,sent.id);assert.equal(await store.unread('lecturer'),0);
    await store.markRead('lecturer',sent.conversationId,0);assert.equal(await store.unread('lecturer'),0);
    const reply=await store.send('student','lecturer','TEST after read',randomUUID());assert.equal(await store.unread('lecturer'),1);
    await store.markRead('lecturer',sent.conversationId,Number.MAX_SAFE_INTEGER);assert.equal(await store.unread('lecturer'),0);
    assert.equal((await store.thread('student','lecturer')).peerReadId,reply.id);
    await db.prepare('UPDATE users SET name=?,role=? WHERE id=?').bind('TEST promoted','admin','student').run();
    const newMessage=await store.send('student','lecturer','TEST promoted account',randomUUID());assert.equal(newMessage.senderRole,'admin');assert.equal(newMessage.senderName,'TEST promoted');
    assert.equal((await store.thread('lecturer','student')).messages[0].senderRole,'student');
    await db.prepare('UPDATE users SET active=0 WHERE id=?').bind('lecturer').run();
    await assert.rejects(store.send('student','lecturer','TEST blocked',randomUUID()),status(403));
    assert.equal((await store.thread('student','lecturer')).peer.active,0);
    assert.equal((await store.send('student','lecturer',sent.body,key)).id,sent.id);
    await assert.rejects(store.thread('student','inactive'),status(404));await assert.rejects(store.thread('student','missing'),status(404));
    await assert.rejects(store.thread('student','student'),status(400));
    await assert.rejects(store.thread('student','lecturer',{before:3,after:4}),status(400));
    await db.prepare('UPDATE users SET active=1 WHERE id=?').bind('lecturer').run();
    await db.prepare('DELETE FROM auth_limits').run();
    for(let i=0;i<58;i++)await store.send('student','lecturer','TEST history '+i,randomUUID());
    const latest=await store.thread('student','lecturer');assert.equal(latest.messages.length,50);assert.ok(latest.hasOlder);
    const older=await store.thread('student','lecturer',{before:latest.messages[0].id});assert.equal(older.messages.length,12);assert.equal(older.hasOlder,false);
    assert.ok(older.messages.at(-1).id<latest.messages[0].id);
    const incremental=await store.thread('student','lecturer',{after:sent.id});assert.equal(incremental.messages.length,61);assert.equal(incremental.hasMore,false);
    await store.send('student','admin','TEST admin contact',randomUUID());
    await store.send('admin','lecturer','TEST admin to lecturer',randomUUID());
    assert.equal((await store.inbox('admin')).conversations.length,2);
    await db.prepare('UPDATE auth_limits SET attempts=60,window_start=? WHERE key=?').bind(Math.floor(Date.now()/60000)*60000,'chat:student').run();
    await assert.rejects(store.send('student','admin','TEST rate limited',randomUUID()),status(429));
    const rows=(await db.prepare('SELECT * FROM chat_messages ORDER BY id').all()).results;
    await initializeDemoDatabase(db);assert.deepEqual((await db.prepare('SELECT * FROM chat_messages ORDER BY id').all()).results,rows);
    assert.deepEqual((await db.prepare('PRAGMA foreign_key_check').all()).results,[]);
    const plans=await db.prepare('EXPLAIN QUERY PLAN SELECT * FROM chat_messages WHERE conversation_id=? AND id<? ORDER BY id DESC LIMIT 50').bind(sent.conversationId,1000).all();
    assert.ok(plans.results.some(row=>row.detail.includes('idx_chat_messages_conversation')));
    const pairPlan=await db.prepare('EXPLAIN QUERY PLAN SELECT * FROM chat_conversations WHERE low_user_id=? AND high_user_id=?').bind('lecturer','student').all();
    assert.ok(pairPlan.results.some(row=>row.detail.includes('idx_chat_pair')));
    await db.prepare('PRAGMA optimize').run();
  }finally{await mf.dispose()}
});
